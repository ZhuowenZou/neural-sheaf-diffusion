"""Collect every finished run of the leak-free campaign into one summary.

Scans results/event_bench/leakfree2/<run>/results.csv (link / TKG / THG runs), the node-property
CSVs under results/leakfree_nodeprop/, and the per-event analyses, and writes

  results/event_bench/results_summary.csv   one row per finished run
  results/event_bench/RESULTS_SUMMARY.md    grouped means +/- std per (dataset, head, core), plus
                                            unfinished / crashed runs

Usage:  python -m exp.collect_results [--root results/event_bench/leakfree2]
The arm labels are derived from the run's own config_json (never from the run name), so a row can
always be traced back to the flags it was trained with.
"""
import argparse
import glob
import json
import os
import re
import time

import numpy as np
import pandas as pd


def _arm(cfg):
    head = "REC on" if cfg.get("recurrency_decoder") else "REC off"
    if cfg.get("model", "faithful") != "faithful":
        return head, "efficient (original) model"
    if int(cfg.get("layers", 2)) == 0 and cfg.get("no_memory"):
        core = "core OFF"
    elif cfg.get("no_memory"):
        core = "no memory"
    elif cfg.get("sheaf_identity"):
        core = "identity maps"
    elif cfg.get("no_delta_t"):
        core = "no Delta_k"
    elif cfg.get("sheaf_conditioning", "history") == "current_only":
        core = "current-only maps"
    else:
        core = "full"
    extras = [k for k in ("emb_in_head", "learn_node_emb") if cfg.get(k)]
    return head, core + (" +" + "+".join(extras) if extras else "")


def collect(root):
    rows, unfinished = [], []
    for log in sorted(glob.glob(os.path.join(root, "*.log"))):
        run = os.path.basename(log)[:-4]
        if re.search(r"(fail\d*|oom|held|retry|queue)$", run) or run.endswith("_queue") or ".fail" in run or ".oom" in run:
            continue
        res = os.path.join(root, run, "results.csv")
        if os.path.exists(res):
            r = pd.read_csv(res).iloc[0]
            try:
                cfg = json.loads(r.get("config_json", "{}"))
            except Exception:
                cfg = {}
            cfg.setdefault("model", "faithful" if "Faithful" in str(r.get("model", "")) else "original")
            if pd.isna(r.get("test_mrr", np.nan)):
                continue  # training-only run (evaluated separately via --eval-only)
            head, core = _arm(cfg)
            rows.append(dict(run=run, dataset=r["dataset"], seed=int(r["seed"]), head=head, core=core,
                             val_mrr=float(r.get("validation_mrr", np.nan)), test_mrr=float(r["test_mrr"]),
                             test_hits10=float(r.get("test_hits10", np.nan)),
                             finished=time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(res)))))
        elif os.path.exists(os.path.join(root, run + "_eval", "results.csv")):
            continue  # training stopped after best.pt; its evaluation lives in <run>_eval
        else:
            txt = open(log, errors="replace").read()
            state = "crashed" if ("Traceback" in txt or "OutOfMemoryError" in txt) else "running/pending"
            ep = re.findall(r"'epoch': (\d+)", txt)
            unfinished.append(dict(run=run, state=state, last_epoch=int(ep[-1]) if ep else 0))
    return pd.DataFrame(rows), pd.DataFrame(unfinished)


def nodeprop(root="results/leakfree_nodeprop"):
    out = []
    for f in sorted(glob.glob(os.path.join(root, "*.csv"))):
        d = pd.read_csv(f)
        if "test_ndcg" in d:
            out.append(dict(file=os.path.basename(f), seeds=len(d), test_ndcg_mean=d.test_ndcg.mean(),
                            test_ndcg_std=d.test_ndcg.std() if len(d) > 1 else np.nan, val_ndcg_mean=d.val_ndcg.mean()))
    return pd.DataFrame(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results/event_bench/leakfree2")
    ap.add_argument("--out-dir", default="results/event_bench")
    args = ap.parse_args()
    runs, unfinished = collect(args.root)
    runs.to_csv(os.path.join(args.out_dir, "results_summary.csv"), index=False)
    lines = ["# Results summary (auto-generated by exp/collect_results.py)", "",
             f"{len(runs)} finished runs under `{args.root}`; arm labels derived from each run's config_json.", ""]
    if len(runs):
        g = (runs.groupby(["dataset", "head", "core"]).test_mrr
             .agg(n="count", mean="mean", std="std", values=lambda v: " / ".join(f"{x:.4f}" for x in v)).reset_index())
        lines += ["## Test MRR by dataset x head x core (mean +/- std over seeds)", "",
                  "| dataset | head | core | n | mean | std | per-seed |", "|---|---|---|---|---|---|---|"]
        for _, r in g.iterrows():
            std = "-" if pd.isna(r["std"]) else f"{r['std']:.4f}"
            lines.append(f"| {r.dataset} | {r['head']} | {r.core} | {r.n} | {r['mean']:.4f} | {std} | {r['values']} |")
    npd = nodeprop()
    if len(npd):
        lines += ["", "## Node property (test NDCG@10)", "", "| file | seeds | mean | std | val mean |", "|---|---|---|---|---|"]
        for _, r in npd.iterrows():
            std = "-" if pd.isna(r.test_ndcg_std) else f"{r.test_ndcg_std:.4f}"
            lines.append(f"| {r.file} | {r.seeds} | {r.test_ndcg_mean:.4f} | {std} | {r.val_ndcg_mean:.4f} |")
    if len(unfinished):
        lines += ["", "## Not finished", "", "| run | state | last epoch |", "|---|---|---|"]
        for _, r in unfinished.iterrows():
            lines.append(f"| {r.run} | {r.state} | {r.last_epoch} |")
    open(os.path.join(args.out_dir, "RESULTS_SUMMARY.md"), "w").write("\n".join(lines) + "\n")
    import hashlib   # stable across processes (Python's hash() is salted per process)
    fp = int(hashlib.md5("|".join(sorted(runs.run)).encode()).hexdigest()[:8], 16) if len(runs) else 0
    print(f"collected {len(runs)} finished runs, {len(unfinished)} unfinished; fingerprint {fp}")


if __name__ == "__main__":
    main()
